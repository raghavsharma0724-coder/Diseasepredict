# ---------------------------------------------------------------------
# Load trained model + encoders ONCE at startup (not per-request)
# ---------------------------------------------------------------------
with open(os.path.join(MODEL_DIR, "disease_model.pkl"), "rb") as f:
    model = pickle.load(f)

with open(os.path.join(MODEL_DIR, "gender_encoder.pkl"), "rb") as f:
    gender_encoder = pickle.load(f)

with open(os.path.join(MODEL_DIR, "disease_encoder.pkl"), "rb") as f:
    disease_encoder = pickle.load(f)

with open(os.path.join(MODEL_DIR, "feature_columns.pkl"), "rb") as f:
    feature_data = pickle.load(f)
    FEATURE_COLUMNS = feature_data["feature_columns"]
    SYMPTOM_COLUMNS = feature_data["symptom_columns"]

# Human-readable labels for symptoms shown in the UI,
# e.g. "excessive_thirst" -> "Excessive Thirst"
SYMPTOM_DISPLAY = {
    symptom: symptom.replace("_", " ").title() for symptom in SYMPTOM_COLUMNS
}

# Load model comparison metrics (generated by train_model.py) for the About page
with open(os.path.join(MODEL_DIR, "metrics.json"), "r") as f:
    MODEL_METRICS = json.load(f)

# Initialize the prediction history database (creates the table if missing)
init_db()

# Initialize the users table (creates it, and adds user_id to predictions if missing)
init_users_table()


# ---------------------------------------------------------------------
# Helper: compute a Low / Medium / High risk level
# ---------------------------------------------------------------------
def compute_risk_level(confidence: float, base_risk: str) -> str:
    """
    Combine the model's prediction confidence with the disease's
    baseline clinical risk to produce a final risk level.

    Logic:
    - Low confidence (<60%) means the model itself is unsure,
      so we never show a scary "High" risk on a shaky prediction.
    - Otherwise, we trust the disease's documented baseline risk.
    """
    if confidence < 60:
        return "Low"
    return base_risk


