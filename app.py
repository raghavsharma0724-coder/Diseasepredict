@app.route("/predict", methods=["GET", "POST"])
@login_required
def predict():
    if request.method == "GET":
        # Show the symptom input form
        return render_template("predict.html", symptoms=SYMPTOM_DISPLAY)

    # ---- POST: handle form submission ----
    try:
        patient_name = request.form.get("patient_name", "").strip()
        age = request.form.get("age", "").strip()
        gender = request.form.get("gender", "").strip()
        selected_symptoms = request.form.getlist("symptoms")

        # ---- Input validation ----
        if not patient_name:
            flash("Please enter the patient's name.")
            return redirect(url_for("predict"))

        if not age or not age.isdigit() or int(age) <= 0 or int(age) > 120:
            flash("Please enter a valid age between 1 and 120.")
            return redirect(url_for("predict"))

        if gender not in ("Male", "Female"):
            flash("Please select a valid gender.")
            return redirect(url_for("predict"))

        if not selected_symptoms:
            flash("Please select at least one symptom to get a prediction.")
            return redirect(url_for("predict"))

        if len(selected_symptoms) < 2:
            flash("For a more reliable prediction, please select at least 2 symptoms.")
            return redirect(url_for("predict"))

        # ---- Build feature vector in the exact column order used during training ----
        age = int(age)
        gender_encoded = gender_encoder.transform([gender])[0]

        feature_row = []
        for col in FEATURE_COLUMNS:
            if col == "Age":
                feature_row.append(age)
            elif col == "Gender":
                feature_row.append(gender_encoded)
            else:
                feature_row.append(1 if col in selected_symptoms else 0)

        # ---- Predict ----
        feature_df = pd.DataFrame([feature_row], columns=FEATURE_COLUMNS)
        prediction_encoded = model.predict(feature_df)[0]
        predicted_disease = disease_encoder.inverse_transform([prediction_encoded])[0]

        # Confidence score = probability of the predicted class
        if hasattr(model, "predict_proba"):
            probabilities = model.predict_proba(feature_df)[0]
            confidence = round(max(probabilities) * 100, 2)
        else:
            confidence = None

        # ---- Fetch disease metadata ----
        info = get_disease_info(predicted_disease)
        risk_level = compute_risk_level(confidence or 0, info["base_risk"])

        # ---- Store result in session, then redirect (Post/Redirect/Get pattern) ----
        session["result"] = {
            "patient_name": patient_name,
            "disease": predicted_disease,
            "confidence": confidence,
            "risk_level": risk_level,
            "age": age,
            "gender": gender,
            "selected_symptoms": [SYMPTOM_DISPLAY[s] for s in selected_symptoms],
            "description": info["description"],
            "causes": info["causes"],
            "precautions": info["precautions"],
            "lifestyle_tips": info["lifestyle_tips"],
            "diet": info["diet"],
            "exercise": info["exercise"],
            "when_to_consult": info["when_to_consult"],
            "specialist": info["specialist"],
        }

        # ---- Save this prediction to history (SQLite) ----
        save_prediction(
            patient_name=patient_name,
            age=age,
            gender=gender,
            symptoms=[SYMPTOM_DISPLAY[s] for s in selected_symptoms],
            disease=predicted_disease,
            confidence=confidence,
            risk_level=risk_level,
            user_id=session.get("user_id"),
        )

        return redirect(url_for("result"))

    except Exception as e:
        # Catch-all error handling so the app never crashes ungracefully
        flash(f"Something went wrong while processing your request: {e}")
        return redirect(url_for("predict"))


@app.route("/result")
def result():
    result_data = session.get("result")
    if not result_data:
        # Prevents users from visiting /result directly without a prediction
        flash("Please submit your symptoms first to view a result.")
        return redirect(url_for("predict"))

    return render_template("result.html", result=result_data)


@app.route("/download-report")
def download_report():
    """Generate and stream the PDF medical report for the current session's result."""
    result_data = session.get("result")
    if not result_data:
        flash("Please complete a prediction first to download a report.")
        return redirect(url_for("predict"))

    pdf_buffer = generate_medical_report_pdf(result_data)
    filename = f"MediPredict_Report_{result_data.get('patient_name', 'Patient').replace(' ', '_')}.pdf"

    return send_file(
        pdf_buffer,
        mimetype="application/pdf",
        as_attachment=True,
        download_name=filename,
    )


